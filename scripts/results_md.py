"""Turn bench/results.csv into docs/RESULTS.md. Never hand-edit RESULTS.md.

Usage: python scripts/results_md.py [--csv bench/results.csv] [--out docs/RESULTS.md]
"""

from __future__ import annotations

import argparse
import csv
import statistics
from datetime import datetime
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]

OUTCOME_MARK = {
    "verified": "✅ verified",
    "rejected_by_verifier": "❌ rejected",
    "no_working_action": "❌ no action",
}


def _host(url: str) -> str:
    return (urlparse(url).netloc or url).removeprefix("www.")


def _minutes(row: dict) -> float | None:
    try:
        return float(row["wall_s"]) / 60
    except (KeyError, TypeError, ValueError):
        return None


def _model_table(rows: list[dict]) -> list[str]:
    models: dict[str, list[dict]] = {}
    for r in rows:
        models.setdefault(r["model"], []).append(r)
    out = [
        "| Model | Runs | Verified | Median time (verified) | Avg repair rounds | Tool errors / run |",
        "|---|---|---|---|---|---|",
    ]
    for model, rs in sorted(models.items()):
        ok = [r for r in rs if r["outcome"] == "verified"]
        mins = [m for r in ok if (m := _minutes(r)) is not None]
        repairs = [int(r["repair_rounds"] or 0) for r in rs]
        errors = [int(r["forge_tool_errors"] or 0) for r in rs]
        out.append(
            f"| `{model}` | {len(rs)} | {len(ok)} "
            f"| {f'{statistics.median(mins):.1f} min' if mins else '—'} "
            f"| {statistics.mean(repairs):.2f} "
            f"| {statistics.mean(errors):.1f} |"
        )
    return out


def _run_table(rows: list[dict]) -> list[str]:
    out = [
        "| When | Site | Goal | Model | Outcome | Action | Checks | Repairs | Time |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(rows, key=lambda r: r.get("timestamp", ""), reverse=True):
        mins = _minutes(r)
        goal = (r.get("goal") or "").strip()
        if len(goal) > 60:
            goal = goal[:57] + "…"
        out.append(
            f"| {r.get('timestamp', '')} | {_host(r.get('site', ''))} | {goal} "
            f"| `{r.get('model', '')}` | {OUTCOME_MARK.get(r.get('outcome', ''), r.get('outcome', ''))} "
            f"| `{r.get('action_id') or '—'}` "
            f"| {r.get('verifier_matched', '')}/{r.get('verifier_checks', '')} "
            f"| {r.get('repair_rounds', '')} "
            f"| {f'{mins:.1f} min' if mins is not None else '—'} |"
        )
    return out


def render(rows: list[dict]) -> str:
    lines = [
        "# Results",
        "",
        f"Generated by `scripts/results_md.py` from `bench/results.csv` "
        f"on {datetime.now().strftime('%d %b %Y %H:%M')}. Do not edit by hand.",
        "",
    ]
    if not rows:
        lines += ["No runs recorded yet. Run `python -m wireforge forge <url> --goal \"...\"` first.", ""]
        return "\n".join(lines)

    verified = [r for r in rows if r["outcome"] == "verified"]
    mins = [m for r in verified if (m := _minutes(r)) is not None]
    lines += [
        f"**{len(rows)}** runs · **{len(verified)}** verified actions across "
        f"**{len({r['site'] for r in verified})}** sites · "
        f"**{sum(1 for r in verified if r.get('type') == 'write')}** write actions"
        + (f" · median **{statistics.median(mins):.1f} min** to a verified action" if mins else ""),
        "",
        "## By model",
        "",
        *_model_table(rows),
        "",
        "## All runs",
        "",
        *_run_table(rows),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--csv", default=ROOT / "bench" / "results.csv", type=Path)
    ap.add_argument("--out", default=ROOT / "docs" / "RESULTS.md", type=Path)
    args = ap.parse_args()

    rows: list[dict] = []
    if args.csv.exists():
        with args.csv.open(encoding="utf-8") as f:
            rows = list(csv.DictReader(f))

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(rows), encoding="utf-8")
    print(f"wrote {args.out} ({len(rows)} runs)")


if __name__ == "__main__":
    main()
